import matplotlib.pyplot as plt

plt.rcParams.update({"font.family": "STIXGeneral", "mathtext.fontset": "stix"})
W, H = 10.6, 2.62
fig = plt.figure(figsize=(W, H), dpi=220)
ax = fig.add_axes([0, 0, 1, 1]); ax.set_xlim(0, W); ax.set_ylim(0, H); ax.axis("off")

def t(x, y, s, ha="left", size=9.2, **kw):
    ax.text(x, y, s.replace("\\%", "%").replace("--", "–"), ha=ha, va="center", size=size, **kw)

t(W / 2, H - 0.16, "TABLE IV", "center", 9.5)
t(W / 2, H - 0.36, "HARDWARE COST OF BINARIZATION: ABLATION OF THE PROPOSED NETWORK ON THE SAME FPGA "
  "(XILINX XC7S75, 50 MHz), GOOGLE SPEECH COMMANDS V2", "center", 7.6)

cols = [0.12, 1.75, 3.95, 4.55, 5.10, 5.65, 6.40, 6.50, 8.05, 8.70, 9.50, 9.60]
align = ["left", "left", "right", "right", "right", "right", "right", "left",
         "right", "right", "right", "left"]
top = H - 0.58
ax.plot([0.08, W - 0.08], [top, top], color="k", lw=1.1)
y1, y2 = top - 0.17, top - 0.42
def grp(x0, x1, label):
    t((x0 + x1) / 2, y1, label, "center", 8.6)
    ax.plot([x0, x1], [y1 - 0.11, y1 - 0.11], color="k", lw=0.5)
grp(4.10, 5.75, "Ops / inference [M]")
grp(5.90, 7.30, "Energy* [μJ]")
grp(8.95, 10.45, "Accuracy [%]")
heads = ["Method", "Binarized layers", "Weights [kbit]", "XNOR", "ADD", "MAC",
         "compute", "(improv.)", "Latency [ms]", "DSP§", "12 classes", ""]
for x, a, h in zip(cols, align, heads):
    t(x if a == "left" else x, y2, h, a, 8.6)
mid = y2 - 0.16
ax.plot([0.08, W - 0.08], [mid, mid], color="k", lw=0.6)
y = mid - 0.22
for c in cells:
    for x, a, s in zip(cols, align, c):
        s = (s.replace("$\\rightarrow$", "→").replace("$\\times$", "×")
              .replace("$^{\\dagger}$", "†").replace("$^{\\ddagger}$", "‡"))
        t(x, y, s, a, 9.0)
    y -= 0.25
bot = y + 0.08
ax.plot([0.08, W - 0.08], [bot, bot], color="k", lw=1.1)
import textwrap
