"""IEEE-style table: what binarization costs and saves, on the same FPGA.

    python docs/paper/make_table_binarization.py

Writes table_binarization.tex (for the paper, booktabs) and
table_binarization.png (preview). Every number is derived here from its
source -- op counts (docs/conv2_int8_compare.md 4, 9.2), the MAC
micro-benchmark (9.6, rtl/bench), accuracies (9.1, 9.5) -- so the two files
cannot drift from each other or from the measurements.
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent

# ---- measurements ---------------------------------------------------------- #
PJ = {"xnor": 1.19, "add": 15.2, "mac": 27.3}          # bench_mac, Vivado, xc7s75
CLK = 50e6
BASE_CYC = 2.87e6                                     # bd_base, on chip
BIN_LAYER_CYC = 122_880                               # B1-B3 + conv2 binary engines
CONV2_BIN_CYC = 20_480
ROWS = [
    # name, binarized, weight bits, xnor, add, mac, acc, latency_cycles, dsp, measured
    ("Binary (proposed)", "B1--B3, Conv2", 375_552,
     3_424_256, 1_441_792, 1_146_880, 82.49, BASE_CYC, 0, True),
    ("Conv2 $\\rightarrow$ INT8", "B1--B3", 445_888,
     2_781_184, 1_560_576, 1_671_168, 82.84,
     BASE_CYC - CONV2_BIN_CYC + 1_856 * 64 + 8_192 * 64, 1, False),
    ("All INT8 (W8A8)", "--", 750_080,
     0, 1_441_792, 4_571_136, 86.68,
     BASE_CYC - BIN_LAYER_CYC + 3_424_256 / 2, 30, False),
]
REF = 2                                               # energy reference row
ACC_REF = 0                                           # accuracy reference row


def energy_uj(r):
    return (r[3] * PJ["xnor"] + r[4] * PJ["add"] + r[5] * PJ["mac"]) * 1e-6


E = [energy_uj(r) for r in ROWS]
cells = []
for i, r in enumerate(ROWS):
    imp = "(ref.)" if i == REF else f"({E[REF] / E[i]:.1f}$\\times$)"
    # difference of the DISPLAYED values, so a reader's subtraction checks out
    d = round(r[6], 1) - round(ROWS[ACC_REF][6], 1)
    acc = "(ref.)" if i == ACC_REF else f"({d:+.1f}\\%)"
    lat = r[7] / CLK * 1e3
    cells.append([
        r[0] + ("" if not r[9] else ""),
        r[1],
        f"{r[2] / 1000:.1f}",
        *[(f"{v / 1e6:.2f}" if v else "--") for v in (r[3], r[4], r[5])],
        f"{E[i]:.1f}", imp,
        f"{lat:.1f}" + ("$^{\\dagger}$" if r[9] else ("$^{\\ddagger}$" if r[8] >= 30 else "")),
        f"{r[8]}",
        f"{r[6]:.1f}\\%", acc,
    ])

# ---- LaTeX ------------------------------------------------------------------ #
tex = r"""% GENERATED by docs/paper/make_table_binarization.py -- do not edit by hand.
% needs \usepackage{booktabs}
\begin{table*}[t]
\caption{Hardware Cost of Binarization: Ablation of the Proposed Network\\
on the Same FPGA (Xilinx XC7S75, 50\,MHz), Google Speech Commands v2}
\label{tab:binarization}
\centering
\setlength{\tabcolsep}{4.2pt}
\begin{tabular}{llr rrr rl r r rl}
\toprule
 & & & \multicolumn{3}{c}{Ops / inference [M]} & \multicolumn{2}{c}{Energy$^{*}$ [$\mu$J]} & & & \multicolumn{2}{c}{Accuracy [\%]} \\
\cmidrule(lr){4-6}\cmidrule(lr){7-8}\cmidrule(lr){11-12}
Method & Binarized layers & Weights [kbit] & XNOR & ADD & MAC & compute & (improv.) & Latency [ms] & DSP$^{\S}$ & 12 classes & \\
\midrule
"""
for c in cells:
    tex += " & ".join(c) + r" \\" + "\n"
tex += r"""\bottomrule
\end{tabular}

\vspace{2pt}
\begin{minipage}{\textwidth}\footnotesize
All three networks have the same topology and 93{,}952 weights; only the precision of the
layers differs. XNOR: 32-bit packed XNOR-popcount term; ADD: INT8 weight $\times$ $\pm1$
activation (sign-controlled add); MAC: INT8 multiply-accumulate.
$^{*}$Dynamic compute energy only: per-operation energy from post-route, vectorless power of
MAC micro-benchmarks on the same device (XNOR %.2f\,pJ, ADD %.1f\,pJ, MAC on DSP48 %.1f\,pJ)
times operation counts; memory access, control and static power are excluded.
$^{\dagger}$Measured on chip (600/600 clips bit-exact with the integer reference).
Other latencies are estimated from cycle counts.
$^{\ddagger}$With two DSP48 per engine; with one, 123\,ms. Matching the binary latency would
need 480 DSP48 (the device has 140).
$^{\S}$DSP48 slices for the layers that are binary in the proposed network; the INT8 tail
(Conv3, Conv4) uses 7 in all three.
Accuracy: test split, 12 classes; W8A8 is 8-bit weights and activations (QAT).
\end{minipage}
\end{table*}
""" % (PJ["xnor"], PJ["add"], PJ["mac"])
(HERE / "table_binarization.tex").write_text(tex)

