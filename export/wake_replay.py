"""Golden clips as a C header, for the STM32 replay test (wake plan step 3).

The first hardware milestone of docs/wake_stm32_plan.md: the STM32 sends
golden clips from its own flash over the link and the FPGA must classify every
one exactly as the Python integer path did -- 600/600, the chip self-test's
standard, but now through STM32 -> UART -> kws_link_rx -> kws_top.

    python -m export.wake_replay                         # bd_base, 600 clips
    python -m export.wake_replay --clips 20 --out /tmp/replay_clips.h

Writes `replay_frames[N][100]` (the native frames; the FPGA adds the padding)
and `replay_expect[N]` (predictions_fixed). 600 clips are 120 KB of flash out
of 1 MB. Standard library only -- runs with Vivado's bundled Python on the
laptop, no torch.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from export.wake_link import NATIVE_T, native_frames

ROOT = Path(__file__).resolve().parents[1]


def render(input_hex: Path, expect: list, n: int, tag: str) -> str:
    rows, lines = [], []
    for c in range(n):
        f = native_frames(input_hex, c)
        rows.append("    {" + ",".join(f"0x{x:04x}" for x in f) + "},")
    lines += [
        f"/* GENERATED by export/wake_replay.py from {tag} -- do not edit.",
        f" * {n} golden clips: native frames (bit k = ch k) and the Python",
        " * integer path's class (predictions_fixed). See docs/wake_stm32_plan.md 4. */",
        "#ifndef REPLAY_CLIPS_H",
        "#define REPLAY_CLIPS_H",
        "",
        "#include <stdint.h>",
        "",
        f"#define REPLAY_N      {n}",
        f"#define REPLAY_FRAMES {NATIVE_T}",
        "",
        "static const uint16_t replay_frames[REPLAY_N][REPLAY_FRAMES] = {",
        *rows,
        "};",
        "",
        "static const uint8_t replay_expect[REPLAY_N] = {",
        "    " + ",".join(str(e) for e in expect[:n]),
        "};",
        "",
        "#endif /* REPLAY_CLIPS_H */",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--vectors", type=Path,
                    default=ROOT / "rtl" / "gen" / "bd_base" / "selftest",
                    help="a golden.py --vectors-only directory")
    ap.add_argument("--clips", type=int, default=600)
    ap.add_argument("--out", type=Path,
                    default=ROOT / "firmware" / "stm32_wake" / "gen" / "replay_clips.h")
    args = ap.parse_args()

    expect = [int(x) for x in (args.vectors / "predictions_fixed.txt").read_text().split()]
    if not 0 < args.clips <= len(expect):
        raise SystemExit(f"--clips must be 1..{len(expect)}")
    if max(expect) > 255:
        raise SystemExit("classes do not fit a byte")
    tag = str(args.vectors.relative_to(ROOT)) if args.vectors.is_relative_to(ROOT) \
        else str(args.vectors)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render(args.vectors / "input.hex", expect, args.clips, tag))
    print(f"wrote {args.out}: {args.clips} clips, "
          f"{args.clips * NATIVE_T * 2 / 1024:.0f} KiB of frames")


if __name__ == "__main__":
    main()
