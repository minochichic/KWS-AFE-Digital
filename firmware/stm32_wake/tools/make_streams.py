"""Stream test inputs (step 3.5, B1): golden clips laid into quiet, frame by frame.

    python -I firmware/stm32_wake/tools/make_streams.py

Writes
  firmware/stm32_wake/gen/stream_clips.h     the streams, for the WAKE_STREAM build
  firmware/stm32_wake/gen/stream_expect.json what the firmware must capture

The firmware feeds one stream frame per 10 ms tick into wake_core in place of
the pins (fresh wake_init at the start), so the board must capture exactly what
experiments/eval_trigger.simulate_triggers captures on the same stream -- that
function is checked frame for frame against wake_core on the Mac
(tests/test_firmware_core.py).

Stream 1 holds the golden clips whose trigger window IS the clip: speech starts
at frame 30 of the clip, so pre=30 cuts out the clip unchanged and the FPGA must
answer predictions_fixed (the trained model's integer answer). Stream 2 holds
clips that start anywhere; there the cut window is a new input, so only the
capture and the link are checked and the class is compared with the true label
for information.

Standard library + numpy (both ship with Vivado's Python).
"""
from __future__ import annotations

import json
import random
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT))
from experiments.eval_trigger import FIRMWARE_POLICY, simulate_triggers  # noqa: E402

SEL = ROOT / "rtl" / "gen" / "bd_base" / "selftest"
OUT = ROOT / "firmware" / "stm32_wake" / "gen"
NATIVE, PAD_LEFT, T = 100, 14, 128
LEAD, GAP, TAIL = 60, 150, 150      # frames of quiet: before, between, after
COUNTED = np.ones(16, bool)


def load():
    words = np.array([int(x, 16) for x in (SEL / "input.hex").read_text().split()],
                     dtype=np.uint32).reshape(-1, T)[:, PAD_LEFT:PAD_LEFT + NATIVE]
    bits = ((words[:, :, None] >> np.arange(16)) & 1).astype(np.uint8)   # [clips, 100, 16]
    pred = [int(x) for x in (SEL / "predictions_fixed.txt").read_text().split()]
    lab = [int(x) for x in (SEL / "labels.txt").read_text().split()]
    return bits, pred, lab


def quiet(n):
    return np.zeros((n, 16), np.uint8)


def aligned(bits) -> list[int]:
    """Clips whose own trigger window, after quiet, starts at the clip's first frame."""
    out = []
    for i in range(len(bits)):
        s = np.concatenate([quiet(LEAD), bits[i], quiet(TAIL)])
        caps = simulate_triggers(s, FIRMWARE_POLICY, COUNTED, len(s))
        if len(caps) == 1 and caps[0].start == LEAD:
            out.append(i)
    return out


def build(bits, ids, gaps):
    parts, place = [quiet(LEAD)], []
    pos = LEAD
    for i, g in zip(ids, gaps):
        place.append((i, pos))
        parts += [bits[i], quiet(g)]
        pos += NATIVE + g
    return np.concatenate(parts), place


def expect(stream, place, pred, lab, need_class: bool):
    caps = simulate_triggers(stream, FIRMWARE_POLICY, COUNTED, len(stream))
    rows = []
    for c in caps:
        frames = [int(sum(int(b) << k for k, b in enumerate(f))) for f in stream[c.start:c.end]]
        hit = [(i, p) for i, p in place if p < c.end and c.start < p + NATIVE]
        clip, at = hit[0] if hit else (None, None)
        exact = clip is not None and at == c.start
        rows.append({"start": c.start, "end": c.end, "frames": frames, "clip": clip,
                     "label": lab[clip] if clip is not None else None,
                     "expect_class": pred[clip] if exact else None})
    # Not every aligned clip stays aligned once others came before it: the background
    # floor (bg_q < 32 does not decay) left by an earlier word delays some onsets by a
    # frame or three. The simulator predicts that too, so those captures are still
    # checked frame for frame -- they just have no known model answer.
    if need_class and not any(r["expect_class"] is not None for r in rows):
        raise SystemExit("stream 1: no capture is a clip itself")
    return rows


def main() -> None:
    bits, pred, lab = load()
    al = aligned(bits)
    rnd = random.Random(35)
    others = rnd.sample([i for i in range(len(bits)) if i not in al], 8)

    s1, p1 = build(bits, al, [GAP] * (len(al) - 1) + [TAIL])
    s2, p2 = build(bits, others, [rnd.randrange(80, 200) for _ in others[:-1]] + [TAIL])
    streams = [("aligned", s1, p1, True), ("anywhere", s2, p2, False)]

    OUT.mkdir(parents=True, exist_ok=True)
    meta, flat, offs = [], [], []
    for name, s, place, need in streams:
        offs.append((len(flat), len(s)))
        flat += [int(sum(int(b) << k for k, b in enumerate(f))) for f in s]
        meta.append({"name": name, "frames": len(s), "clips": [i for i, _ in place],
                     "captures": expect(s, place, pred, lab, need)})

    lines = ["/* GENERATED by firmware/stm32_wake/tools/make_streams.py -- do not edit. */",
             "#ifndef STREAM_CLIPS_H", "#define STREAM_CLIPS_H", "#include <stdint.h>",
             f"#define STREAM_N {len(streams)}",
             "static const uint32_t stream_off[STREAM_N] = {" + ",".join(str(o) for o, _ in offs) + "};",
             "static const uint32_t stream_len[STREAM_N] = {" + ",".join(str(n) for _, n in offs) + "};",
             f"static const uint16_t stream_frames[{len(flat)}] = {{"]
    for k in range(0, len(flat), 16):
        lines.append("    " + ",".join(f"0x{v:04x}" for v in flat[k:k + 16]) + ",")
    lines += ["};", "#endif", ""]
    (OUT / "stream_clips.h").write_text("\n".join(lines))
    (OUT / "stream_expect.json").write_text(json.dumps(meta, indent=1))

    for i, m in enumerate(meta, 1):
        n_cls = sum(c["expect_class"] is not None for c in m["captures"])
        print(f"stream {i} ({m['name']}): {m['frames']} frames = {m['frames'] / 100:.1f} s, "
              f"{len(m['clips'])} clips, {len(m['captures'])} expected captures, "
              f"{n_cls} with a known model answer")


if __name__ == "__main__":
    main()
